"""Publish only the self-contained preview to a separate gh-pages branch.

No checkout, index mutation, main-branch update, force push, PDF, or credentials.
Requires the existing authenticated HTTPS Git connection.
"""

from io import BytesIO
from pathlib import Path
import json
import subprocess
import zipfile


ROOT = Path(__file__).resolve().parents[1]
BRANCH = "gh-pages"
MARKER = {"project": "Sofi28", "purpose": "vienna-gift-preview", "format": 1}


def git(*args, data=None):
    return subprocess.run(
        ["git", *args], cwd=ROOT, input=data, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, check=True,
    ).stdout


def publish():
    html = (ROOT / "dist-standalone/index.html").read_bytes()
    if not html or b"data:application/pdf" in html:
        raise RuntimeError("Missing HTML or embedded PDF: refusing to publish.")

    remote = git("ls-remote", "--heads", "origin", f"refs/heads/{BRANCH}").decode().strip()
    parent = remote.split()[0] if remote else None
    if parent:
        git("fetch", "--no-tags", "origin", f"refs/heads/{BRANCH}")
        try:
            marker = json.loads(git("show", f"{parent}:.preview-managed.json"))
        except (subprocess.CalledProcessError, json.JSONDecodeError) as error:
            raise RuntimeError("Existing gh-pages branch is not managed by this exporter; left untouched.") from error
        if marker != MARKER:
            raise RuntimeError("Existing gh-pages branch belongs to another workflow; left untouched.")

    archive = BytesIO()
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zipped:
        zipped.writestr("Viena.html", html)
        zipped.writestr("LEEME.txt", "Descomprime y abre Viena.html en tu navegador. No requiere servidor.\n")

    readme = """# Viena — preview

Self-contained gift website. No ticket PDF, admission codes, order identifiers or buyer details are included.

## Open in a browser

In repository Settings → Pages, choose **Deploy from a branch**, **gh-pages**, **/ (root)** and Save.
GitHub Pages availability depends on the repository's visibility and account plan.
The page is not live until GitHub confirms a successful Pages deployment.

## Download instead

Download `Viena.zip` from this branch, unzip it and open `Viena.html` locally.
The source application's main branch is unchanged.

This branch is generated by `scripts/publish-preview.py` in the development checkout.
"""
    files = {
        ".nojekyll": b"",
        ".preview-managed.json": (json.dumps(MARKER, indent=2) + "\n").encode(),
        "README.md": readme.encode(),
        "Viena.zip": archive.getvalue(),
        "index.html": html,
    }
    entries = []
    for name, contents in sorted(files.items()):
        blob = git("hash-object", "-w", "--stdin", data=contents).decode().strip()
        entries.append(f"100644 blob {blob}\t{name}\n")
    tree = git("mktree", data="".join(entries).encode()).decode().strip()
    args = ["-c", "user.name=Codex", "-c", "user.email=codex@users.noreply.github.com", "commit-tree", tree]
    if parent:
        args += ["-p", parent]
    commit = git(*args, data=b"Publish self-contained Vienna gift preview\n").decode().strip()
    # The recovery ref preserves this export locally if the remote write fails.
    git("update-ref", "refs/codex/vienna-preview", commit)
    result = subprocess.run(
        ["git", "push", "origin", f"{commit}:refs/heads/{BRANCH}"],
        cwd=ROOT, check=True,
    )
    print(f"Preview branch published: {BRANCH}")
    print(f"Commit: {commit}")
    print("Files: " + ", ".join(files))
    print("Pages activation and deployment still need to be verified.")


if __name__ == "__main__":
    publish()
